export type PixelTextAlign = 'left' | 'center' | 'right'

export function measurePixelText(text: string, scale = 2): number {
  if (!Number.isInteger(scale) || scale < 1) throw new Error('Skala fontu bitmapowego musi być dodatnią liczbą całkowitą.')
  return Math.max(0, text.length * 6 * scale - scale)
}

export function drawPixelText(
  context: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 2,
  align: PixelTextAlign = 'left',
): void {
  const normalized = text.toUpperCase()
  const width = measurePixelText(normalized, scale)
  const startX = Math.round(x - (align === 'center' ? width / 2 : align === 'right' ? width : 0))
  const startY = Math.round(y)
  context.fillStyle = color
  for (let glyphIndex = 0; glyphIndex < normalized.length; glyphIndex += 1) {
    const glyph = GLYPHS[normalized[glyphIndex] ?? '?'] ?? GLYPHS['?']
    if (!glyph) continue
    for (let row = 0; row < glyph.length; row += 1) {
      const pixels = glyph[row]
      if (!pixels) continue
      for (let column = 0; column < pixels.length; column += 1) {
        if (pixels[column] === '1') {
          context.fillRect(startX + (glyphIndex * 6 + column) * scale, startY + row * scale, scale, scale)
        }
      }
    }
  }
}
